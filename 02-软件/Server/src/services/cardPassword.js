/**
 * 卡密的形态规则 —— **全仓唯一一份**。
 *
 * 卡密会直接拼进文件名和 URL：
 *   · `{ygoproDir}\{卡密}.jpg`
 *   · `{thumbDir}\YGOPro\{卡密}.webp`
 * 所以它本来就是一道**路径穿越防线**，不是「数字比较整齐」的美观问题。
 *
 * ---------- V1.2.73 放宽 ----------
 * 以前是 `/^\d{1,12}$/`（纯数字）。那是从「官方 8 位密码」推出来的，但用户手工新增
 * 身份时那个输入框的原话是「输入 8 位卡牌编码或者是输入其他的一个代号」——
 * 既然**代号**能填，**编号**（`AT03-JP009`）自然也该能当卡密用。于是改成白名单：
 *
 *     字母 / 数字 / 下划线 / 短横线，1–64 位
 *
 * **不能再宽**：`/ \ . :`、空格、以及 Windows 文件名非法字符（`< > " | ? *`）
 * 全部排除在外，否则 `path.join(ygoproDir, 卡密 + '.jpg')` 就真的能被穿出去。
 * 想再放宽的人先看这一句，再去看 `services/cardUniques.js` 顶上那段身份规则。
 *
 * ---------- 为什么抽成一个文件 ----------
 * 这道校验全仓有 8 个点（见下面 module.exports 的注释）。各写一份的话，
 * 「放宽的是哪几处、漏了哪一处」迟早对不上 —— 而漏掉的那一处会往库里插一个
 * 带路径字符的卡密，让所有拼卡图 URL 的地方一起失配。改这里，8 处同时生效。
 */

/** 卡密的合法形态。`-` 放在字符组**末尾**才是字面量，别挪位置。 */
const 卡密正则 = /^[A-Za-z0-9_-]{1,64}$/;

/** 给用户看的形态说明。各处报错文案统一引用它，别各自手写一遍。 */
const 卡密说明 = '只能是字母、数字、下划线或短横线，1–64 位';

/**
 * 卡密合法（**非空**才算合法）。
 * 要「允许留空」的场景（改写目录行、清空卡密）请用下面那个 `卡密可留空` ——
 * 判定「无卡密行」另有 `services/cardUniques.无卡密条件`，别拿这个当它。
 */
const 卡密合法 = (s) => 卡密正则.test(String(s == null ? '' : s));

/** 合法，或者留空。留空是合法动作（清空卡密 / 没填），不是故障。 */
const 卡密可留空 = (s) => {
  const v = String(s == null ? '' : s);
  return !v || 卡密正则.test(v);
};

module.exports = { 卡密正则, 卡密说明, 卡密合法, 卡密可留空 };
